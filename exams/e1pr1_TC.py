    D_calc = U.T @ A @ Vt.T
    
    print(D_calc)
    
    S_mat = np.zeros((m, n))
    np.fill_diagonal(S_mat, S)    
    A_rec = U @ S_mat @ Vt
    
    print(A_rec)
    
    return D_calc
    
